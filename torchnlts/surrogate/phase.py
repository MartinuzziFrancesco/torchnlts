"""Phase-randomized ("random Fourier phase") surrogate data, from
observed data.

Reference: Theiler, J., Eubank, S., Longtin, A., Galdrikian, B. & Farmer,
J.D. (1992), "Testing for nonlinearity in time series: the method of
surrogate data", Physica D 58(1-4), 77-94: randomize the Fourier phase of
a signal while keeping its Fourier magnitude (and therefore its power
spectrum / autocorrelation function) fixed, producing a surrogate whose
linear statistics match the original but whose nonlinear structure is
destroyed. Testing a nonlinear statistic on the original signal against
its distribution over many such surrogates is a test of the null
hypothesis that the signal was generated by a linear Gaussian process.

Matches TimeseriesSurrogates.jl's ``RandomFourier`` at its default
``phases=true`` (the only variant implemented here -- its
``phases=false`` random-*amplitude* variant is a distinct, less common
method the cited paper doesn't define, not ported): center the signal,
take its real FFT (``rfft``), draw a fresh phase uniform on
``[0, 2*pi)`` *independently for every frequency bin* -- including the
zero-frequency (DC) bin and, when ``num_points`` is even, the Nyquist
bin -- multiply the unchanged magnitude by that phase, invert
(``irfft``), and add the mean back. Confirmed, by reading its source,
that TimeseriesSurrogates.jl does not special-case those two bins
either.

That choice has a real, confirmed consequence, not merely a theoretical
one: assigning a non-real phase to a bin that Hermitian symmetry
requires to be real (DC and, when it exists, Nyquist) is mathematically
inconsistent, and ``irfft`` resolves that inconsistency silently rather
than erroring. Hand-verified (see this module's tests) and confirmed by
running TimeseriesSurrogates.jl's own ``RandomFourier`` on the same
input: interior bins' magnitude is preserved by the round trip exactly;
the DC bin is preserved only approximately (its magnitude is dominated
by ``num_points * mean``, which swamps the tiny near-zero
centered-signal DC term whose phase was actually randomized); and the
Nyquist bin's magnitude is *not* preserved at all. Julia's reference
implementation shows the identical pattern on the same input, so this is
a shared, inherited property of the classical algorithm's literal,
unmodified form, not a defect introduced by this port.
"""

from __future__ import annotations

import math

import torch

from torchnlts._shape import _ensure_batched


def phase_randomized_surrogate(trajectory, generator: torch.Generator | None = None) -> torch.Tensor:
    """Phase-randomized surrogate of ``trajectory``.

    Gradient class: none, by policy rather than mathematical necessity --
    this subpackage is declared analysis-only/non-differentiable by
    design. For a *fixed* random
    phase draw, the map from ``trajectory`` to the surrogate is itself
    ordinary differentiable autodiff (the random phase is independent
    noise, not a function of ``trajectory``, so it doesn't block
    gradient flow through the magnitude computation); this class is a
    deliberate contract, not a claim that autograd fails here.

    Args:
        trajectory: Shape ``[T]``, ``[T, D]``, or ``[B, T, D]``, real
            floating-point dtype (``float32``/``float64``; integer,
            complex, and half/bfloat16 inputs aren't supported --
            ``rfft`` or ``.mean()`` raises naturally). A tensor, numpy
            array, or pandas Series/DataFrame. Each feature channel
            (and batch element) is phase-randomized independently --
            this is the univariate method applied per-channel, not a
            joint multivariate surrogate that preserves cross-channel
            correlation.
        generator: Optional ``torch.Generator`` for the random phase
            draw, forwarded to ``torch.rand``. Defaults to the global
            RNG (reproducible via ``torch.manual_seed``). Passing an
            explicit ``generator`` advances *its own* state on every
            call, so reusing the same generator object across two calls
            gives two different surrogates, not the same one twice --
            for a reproducible surrogate, pass a freshly re-seeded
            generator (or reset the global seed) before each call.

    Returns:
        Surrogate of the same shape and dtype as ``trajectory``. See the
        module docstring for the confirmed exact/approximate/broken
        magnitude-preservation split across interior, DC, and Nyquist
        bins.

    Raises:
        ValueError: If ``trajectory`` is not shape ``[T]``, ``[T, D]``,
            or ``[B, T, D]``.
    """
    batched, ndim = _ensure_batched(trajectory)
    num_points = batched.shape[-2]
    mean = batched.mean(dim=-2, keepdim=True)
    spectrum = torch.fft.rfft(batched - mean, dim=-2)
    magnitude = spectrum.abs()
    phase = torch.rand(magnitude.shape, generator=generator, dtype=magnitude.dtype, device=magnitude.device)
    phase = phase * (2.0 * math.pi)
    shuffled = magnitude * torch.exp(1j * phase)
    surrogate = torch.fft.irfft(shuffled, n=num_points, dim=-2) + mean
    # Not `_restore_batch`: that helper only undoes the leading batch
    # dim, for functions whose output has a *different* trailing shape
    # than the input (e.g. delay_embedding's [T] -> [num_embedded,
    # embedding_dim]). This function is shape-preserving -- its output
    # must round-trip [T] -> [T] and [T, D] -> [T, D] exactly, not stay
    # 2D/3D, so both dims _ensure_batched added need undoing here.
    if ndim == 1:
        return surrogate.squeeze(0).squeeze(-1)
    if ndim == 2:
        return surrogate.squeeze(0)
    return surrogate
